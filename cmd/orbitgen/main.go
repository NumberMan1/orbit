// Command orbitgen generates message/handler bindings from a JSON manifest.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"

	"github.com/NumberMan1/orbit/internal/protogen"
)

func main() {
	input := flag.String("in", "messages.json", "JSON manifest")
	output := flag.String("out", "bindings_gen.go", "generated Go file")
	check := flag.Bool("check", false, "fail when generated output differs, without writing")
	flag.Parse()
	if err := run(*input, *output, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(input, output string, check bool) error {
	f, err := os.Open(input)
	if err != nil {
		return err
	}
	defer f.Close()
	generated, err := protogen.Generate(f)
	if err != nil {
		return err
	}
	existing, readErr := os.ReadFile(output)
	if check {
		if readErr != nil {
			return readErr
		}
		if !bytes.Equal(existing, generated) {
			return fmt.Errorf("orbitgen: %s is out of date", output)
		}
		return nil
	}
	if readErr != nil && !os.IsNotExist(readErr) {
		return readErr
	}
	if readErr == nil && !bytes.HasPrefix(existing, []byte("// Code generated by orbitgen; DO NOT EDIT.")) {
		return fmt.Errorf("orbitgen: refusing to overwrite handwritten file %s", output)
	}
	return os.WriteFile(output, generated, 0644)
}
