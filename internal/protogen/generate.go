// Package protogen generates explicit registry bindings from a small JSON manifest.
package protogen

import (
	"bytes"
	"encoding/json/v2"
	"errors"
	"fmt"
	"go/format"
	"go/token"
	"io"
	"sort"
	"strconv"
	"strings"
)

// Manifest names an output package, optional type imports and message bindings.
type Manifest struct {
	Package  string            `json:"package"`
	Imports  map[string]string `json:"imports"`
	Messages []Message         `json:"messages"`
}

// Message binds an ID to an existing Go struct type. Handler is optional; response
// messages usually omit it. Codec is "json" or "protobuf"; ID zero is reserved.
type Message struct {
	ID      uint16 `json:"id"`
	Type    string `json:"type"`
	Codec   string `json:"codec"`
	Handler string `json:"handler"`
}

// Generate validates a bounded manifest and emits deterministic, gofmt'd source.
// It generates registration code only, never application models or wire schemas.
func Generate(reader io.Reader) ([]byte, error) {
	b, err := io.ReadAll(io.LimitReader(reader, (1<<20)+1))
	if err != nil {
		return nil, err
	}
	if len(b) > 1<<20 {
		return nil, errors.New("orbitgen: manifest too large")
	}
	var m Manifest
	if err := json.Unmarshal(b, &m, json.RejectUnknownMembers(true)); err != nil {
		return nil, err
	}
	if !token.IsIdentifier(m.Package) || m.Package == "_" || len(m.Messages) == 0 {
		return nil, errors.New("orbitgen: package and messages required")
	}
	reserved := map[string]bool{"context": true, "fmt": true, "codec": true, "socket": true}
	for alias, path := range m.Imports {
		if !token.IsIdentifier(alias) || alias == "_" || reserved[alias] || path == "" || strings.ContainsAny(path, "\"\\\n\r\t ") {
			return nil, errors.New("orbitgen: invalid import")
		}
	}
	ids, types, handlers, usedImports := map[uint16]bool{}, map[string]bool{}, map[string]bool{}, map[string]bool{}
	for _, msg := range m.Messages {
		if msg.ID == 0 || ids[msg.ID] || types[msg.Type] {
			return nil, errors.New("orbitgen: duplicate ID/type or zero ID")
		}
		ids[msg.ID], types[msg.Type] = true, true
		parts := strings.Split(msg.Type, ".")
		if len(parts) > 2 {
			return nil, errors.New("orbitgen: type must be Name or alias.Name")
		}
		for _, part := range parts {
			if !token.IsIdentifier(part) || part == "_" {
				return nil, errors.New("orbitgen: invalid type")
			}
		}
		if len(parts) == 2 {
			if _, ok := m.Imports[parts[0]]; !ok {
				return nil, errors.New("orbitgen: missing type import")
			}
			usedImports[parts[0]] = true
		}
		if msg.Codec != "json" && msg.Codec != "protobuf" {
			return nil, errors.New("orbitgen: unknown codec")
		}
		if msg.Handler != "" {
			if !token.IsIdentifier(msg.Handler) || !token.IsExported(msg.Handler) || handlers[msg.Handler] {
				return nil, errors.New("orbitgen: handlers must be unique exported identifiers")
			}
			handlers[msg.Handler] = true
		}
	}
	if len(usedImports) != len(m.Imports) {
		return nil, errors.New("orbitgen: unused import")
	}
	sort.Slice(m.Messages, func(i, j int) bool { return m.Messages[i].ID < m.Messages[j].ID })
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by orbitgen; DO NOT EDIT.\npackage %s\nimport (\n", m.Package)
	out.WriteString("\"github.com/NumberMan1/orbit/codec\"\n")
	if len(handlers) > 0 {
		out.WriteString("\"context\"\n\"fmt\"\n\"github.com/NumberMan1/orbit/socket\"\n")
	}
	var aliases []string
	for alias := range m.Imports {
		aliases = append(aliases, alias)
	}
	sort.Strings(aliases)
	for _, alias := range aliases {
		fmt.Fprintf(&out, "%s %s\n", alias, strconv.Quote(m.Imports[alias]))
	}
	out.WriteString(")\n// RegisterMessages registers message types in ID order; use a fresh registry.\nfunc RegisterMessages(r *codec.Registry) error {\n")
	for _, msg := range m.Messages {
		codecName := "JSON"
		if msg.Codec == "protobuf" {
			codecName = "Protobuf"
		}
		fmt.Fprintf(&out, "if err:=r.Register(%d, (*%s)(nil), codec.%s{}); err!=nil{return err}\n", msg.ID, msg.Type, codecName)
	}
	out.WriteString("return nil\n}\n")
	if len(handlers) > 0 {
		out.WriteString("// Handlers supplies application callbacks for inbound messages.\ntype Handlers struct {\n")
		for _, msg := range m.Messages {
			if msg.Handler != "" {
				fmt.Fprintf(&out, "// %s handles message ID %d.\n%s func(context.Context, socket.MessageEvent) error\n", msg.Handler, msg.ID, msg.Handler)
			}
		}
		out.WriteString("}\n// RegisterHandlers binds callbacks; use a fresh router and a populated registry.\nfunc RegisterHandlers(router *socket.Router, registry *codec.Registry, handlers Handlers) error {\n")
		out.WriteString("if router==nil || registry==nil {return fmt.Errorf(\"orbitgen: router and registry required\")}\n")
		for _, msg := range m.Messages {
			if msg.Handler != "" {
				fmt.Fprintf(&out, "if handlers.%s==nil {return fmt.Errorf(\"orbitgen: handler %s required\")}\n", msg.Handler, msg.Handler)
			}
		}
		for _, msg := range m.Messages {
			if msg.Handler != "" {
				fmt.Fprintf(&out, "{ h,err:=socket.DecodeHandler(registry,handlers.%s); if err!=nil{return err}; if err=router.Register(%d,h);err!=nil{return err} }\n", msg.Handler, msg.ID)
			}
		}
		out.WriteString("return nil\n}\n")
	}
	return format.Source(out.Bytes())
}
